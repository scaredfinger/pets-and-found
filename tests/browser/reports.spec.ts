import { expect, test } from '@playwright/test'

test('visitor can publish, filter, and view a redacted animal report', async ({ page }) => {
  await page.goto('/reports/new')
  await page.getByLabel('Type').selectOption('lost')
  await page.getByLabel('Species').selectOption('dog')
  await page.getByLabel('Traits').fill('brown, blue collar')
  await page.getByLabel('Location in Mallorca').fill('Palma, Mallorca')
  await page.getByLabel('Event date and time').fill('2026-01-01T10:30')
  await page.getByLabel('Description').fill('Brown dog with a blue collar')
  await page.getByLabel('Latitude').fill('39.5696')
  await page.getByLabel('Longitude').fill('2.6502')
  await page.getByLabel('Your name').fill('Private Reporter')
  await page.getByLabel('Email').fill('private@example.test')
  await page.getByRole('button', { name: 'Publish report' }).click()
  await expect(page).toHaveURL(/\/reports\/\d+$/)
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('lost dog')
  await expect(page.getByText('Brown dog with a blue collar')).toBeVisible()
  await expect(page.getByText('Traits: brown, blue collar')).toBeVisible()
  await expect(page.getByText('Location: Palma, Mallorca')).toBeVisible()
  await expect(page.locator('body')).not.toContainText('Private Reporter')
  await expect(page.locator('body')).not.toContainText('private@example.test')
  await expect(page.locator('body')).not.toContainText('39.5696')
  await page.getByRole('button', { name: 'Resolve report' }).click()
  await expect(page.getByText('Status: resolved')).toBeVisible()
  await page.getByRole('link', { name: 'Reports' }).click()
  await page.getByLabel('Type').selectOption('lost')
  await page.getByLabel('Species').selectOption('dog')
  await page.getByRole('button', { name: 'Filter' }).click()
  await expect(page.getByRole('link', { name: 'lost dog' }).first()).toBeVisible()
})
